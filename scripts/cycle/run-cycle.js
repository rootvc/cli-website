// ============================================================================
// Smoke gate
//
// Runs the cycle-test suite against the drafted artifact directory and
// the source-scan deny-list. Returns `{ passed: boolean, failures: string[] }`.
// On pass, the orchestrator proceeds to freeze. On fail, the failure list
// is included in the next Author retry's critique.
// ============================================================================

function runSmokeGate(artifactPath) {
  const failures = [];

  // Source-scan first (fast, deterministic, no test runner). Failures here
  // are formatted into a critique the Author can act on directly.
  const scanResult = scanArtifact(artifactPath);
  if (scanResult.violations.length > 0) {
    failures.push(
      ...scanResult.violations.map(
        (v) => `source-scan violation: ${v.file}:${v.line} ${v.label} — ${v.suggestedFix}`
      )
    );
  }

  // Vitest smoke suite. We shell out so vitest's own process boundary
  // applies; this matches `npm run smoke`.
  try {
    execSync(
      `ARTIFACT_PATH=${JSON.stringify(artifactPath)} npx vitest run tests/cycle/`,
      {
        cwd: REPO_ROOT,
        stdio: "pipe",
        encoding: "utf8",
        env: { ...process.env, ARTIFACT_PATH: artifactPath },
      }
    );
  } catch (err) {
    const output = (err.stdout || "") + (err.stderr || "");
    failures.push(
      `smoke-test failure (see output):\n${truncate(output, 4000)}`
    );
  }

  return { passed: failures.length === 0, failures };
}

function truncate(s, n) {
  if (!s) return "";
  if (s.length <= n) return s;
  return s.substring(0, n) + "... [truncated]";
}

// ============================================================================
// Revision loop
// ============================================================================

async function runRevisionLoop({
  configs,
  performanceLog,
  topicalBrief,
  maxRetries,
  authorCall,
  editorCall,
  smokeGateFn,
  freezeFn,
  outputDir,
  cspNonce,
}) {
  const diversity = slicePerformanceLog(performanceLog);
  let attempt = 0;
  let priorCritique = null;
  let lastAuthorOutput = null;
  let lastValidationErrors = null;

  while (attempt <= maxRetries) {
    const retryCounter = attempt;

    // 1. Call Author.
    const authorOutput = await authorCall({
      configs,
      performanceLog,
      topicalBrief,
      retryCounter,
      priorCritique,
      diversity,
    });
    lastAuthorOutput = authorOutput;

    // 2. Validate against schema.
    const validation = validateAuthorOutput(authorOutput);
    lastValidationErrors = validation.errors;
    if (!validation.valid) {
      priorCritique = formatSchemaErrorsAsCritique(validation.errors);
      attempt++;
      continue;
    }

    // 3. Inject the resolved CSP nonce into the meta so freeze can apply it.
    //    Author leaves the placeholder `{{CSP_NONCE}}` in script tags;
    //    freeze substitutes it. meta.csp_nonce gets the resolved value here.
    const finalOutput = {
      ...authorOutput,
      meta: { ...authorOutput.meta, csp_nonce: cspNonce },
    };

    // 4. Freeze to a working directory. This catches Author errors like
    //    "emitted a <script> tag without the nonce placeholder" before
    //    we run the smoke gate.
    let freezeError = null;
    try {
      // Wipe any prior attempt's contents to keep the smoke gate clean.
      if (fs.existsSync(outputDir)) {
        fs.rmSync(outputDir, { recursive: true, force: true });
      }
      fs.mkdirSync(outputDir, { recursive: true });
      freezeFn({ outputDir, authorOutput: finalOutput });
    } catch (err) {
      freezeError = err.message;
    }
    if (freezeError) {
      priorCritique = `freeze-archive rejected the draft: ${freezeError}`;
      attempt++;
      continue;
    }

    // 5. Smoke gate (smoke tests + source scan).
    const smokeResult = smokeGateFn(outputDir);
    if (!smokeResult.passed) {
      priorCritique = formatSmokeFailuresAsCritique(smokeResult.failures);
      attempt++;
      continue;
    }

    // 6. Editor pass.
    const editorDecision = await editorCall({
      authorOutput: finalOutput,
      configs,
      diversitySlice: diversity,
      smokeResult,
    });

    if (editorDecision.decision === "approve") {
      return {
        success: true,
        authorOutput: finalOutput,
        editorDecision,
        smokeResult,
        retriesUsed: attempt,
      };
    }

    // 7. Editor rejected — retry.
    priorCritique = formatEditorRejectAsCritique(editorDecision);
    attempt++;
  }

  // Loop exhausted.
  return {
    success: false,
    failureReason: `Revision loop exhausted after ${attempt} attempts. Last critique: ${truncate(
      priorCritique || "(none)",
      1000
    )}`,
    retriesUsed: attempt,
    lastAuthorOutput,
    lastValidationErrors,
  };
}

function formatSchemaErrorsAsCritique(errors) {
  return [
    "Your output did not match the required schema. Fix each error and try again:",
    ...errors.map((e) => `  - ${e}`),
    "",
    "Refer to scripts/cycle/output-schema.js for the exact shape.",
  ].join("\n");
}

function formatSmokeFailuresAsCritique(failures) {
  return [
    "Smoke tests rejected the draft. Address each failure on retry:",
    ...failures.map((f) => `  - ${f}`),
  ].join("\n");
}

function formatEditorRejectAsCritique(editorDecision) {
  return [
    "The Editor rejected the draft. Their critique:",
    editorDecision.critique || "(no critique provided)",
    editorDecision.sensitivity_check
      ? `Sensitivity check: ${editorDecision.sensitivity_check}`
      : "",
  ]
    .filter(Boolean)
    .join("\n");
}

// ============================================================================
// Main entry
// ============================================================================

async function main(rawArgv = process.argv.slice(2), overrides = {}) {
  let opts;
  try {
    opts = parseCliArgs(rawArgv);
  } catch (err) {
    process.stderr.write(`run-cycle: ${err.message}\n`);
    return 4;
  }

  const cycleDate = opts.artifactDate || todayUtcIso();
  if (!isValidDateString(cycleDate)) {
    process.stderr.write(`run-cycle: invalid --artifact-date: ${cycleDate}\n`);
    return 4;
  }

  let configs;
  try {
    configs = overrides.configs || readAllConfigs();
  } catch (err) {
    process.stderr.write(`run-cycle: config read failed: ${err.message}\n`);
    return 4;
  }

  const archiveRoot = path.join(REPO_ROOT, "archive");
  const performanceLog = overrides.performanceLog || assemblePerformanceLog(archiveRoot);
  const topicalBrief = overrides.topicalBrief || (await (overrides.topicalFn || fetchTopicalBrief)());

  // Output dir: dry-run uses /tmp/; real runs use archive/YYYY-MM-DD/.
  const outputDir = overrides.outputDir
    || (opts.dryRun
      ? path.join("/tmp", `cycle-dryrun-${cycleDate}-${process.pid}`)
      : path.join(archiveRoot, cycleDate));

  // Per-run CSP nonce.
  const cspNonce = overrides.cspNonce || generateCspNonce();

  // Stub callables — overridable for tests.
  const authorCall = overrides.authorCall
    || ((input) => defaultAuthorStub({
      ...input,
      fixturePath: opts.fixturePath || (opts.dryRun ? null : null),
    }));
  const editorCall = overrides.editorCall || defaultEditorStub;
  const smokeGateFn = overrides.smokeGateFn || runSmokeGate;
  const freezeFn = overrides.freezeFn || freeze;

  const loopResult = await runRevisionLoop({
    configs,
    performanceLog,
    topicalBrief,
    maxRetries: opts.maxRetries,
    authorCall,
    editorCall,
    smokeGateFn,
    freezeFn,
    outputDir,
    cspNonce,
  });

  if (!loopResult.success) {
    const summary = {
      success: false,
      cycle_date: cycleDate,
      output_dir: null,
      theme_name: null,
      topical: null,
      retries_used: loopResult.retriesUsed,
      max_retries: opts.maxRetries,
      failure_reason: loopResult.failureReason,
      dry_run: opts.dryRun,
      max_turns: MAX_TURNS,
      max_run_minutes: MAX_RUN_MINUTES,
    };
    // Clean up any partially-written draft.
    if (fs.existsSync(outputDir) && opts.dryRun) {
      fs.rmSync(outputDir, { recursive: true, force: true });
    }
    process.stdout.write(JSON.stringify(summary) + "\n");
    // Distinguish exit codes per the file header.
    if (loopResult.lastValidationErrors && loopResult.lastValidationErrors.length > 0) {
      return 2;
    }
    return 3;
  }

  // Success — archive directory is already written by the freeze step
  // inside the revision loop. In dry-run, leave the temp directory for
  // inspection.
  const summary = {
    success: true,
    cycle_date: cycleDate,
    output_dir: outputDir,
    artifact_path: outputDir,
    theme_name: loopResult.authorOutput.meta.theme_name,
    topical: !!loopResult.authorOutput.meta.topical,
    topical_hook: loopResult.authorOutput.meta.topical_hook || null,
    retries_used: loopResult.retriesUsed,
    max_retries: opts.maxRetries,
    dry_run: opts.dryRun,
    max_turns: MAX_TURNS,
    max_run_minutes: MAX_RUN_MINUTES,
    press_kit: {
      tweet_draft: loopResult.authorOutput.social.tweet_draft,
      screenshot_brief: loopResult.authorOutput.social.screenshot_brief,
    },
    files_written: fs.existsSync(outputDir)
      ? fs.readdirSync(outputDir).sort()
      : [],
  };

  // Stage files but DO NOT commit/push (U6 workflow handles git ops).
  // Production runs perform `git add` separately; tests don't need it.
  if (!opts.dryRun && !overrides.skipStage) {
    try {
      stageArchive(outputDir);
    } catch (err) {
      // Staging failure is non-fatal — surface it but mark success.
      summary.stage_warning = err.message;
    }
  }

  process.stdout.write(JSON.stringify(summary) + "\n");
  return 0;
}

function stageArchive(outputDir) {
  // We use the git CLI directly so this matches what a developer would do.
  // No commit, no push — just stage.
  const rel = path.relative(REPO_ROOT, outputDir);
  execSync(`git add ${JSON.stringify(rel)}`, { cwd: REPO_ROOT, stdio: "pipe" });
}

