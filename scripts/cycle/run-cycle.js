// Lightweight template renderer used by both this orchestrator and the
// weekly-cycle.yml workflow. Substitutes `${key}` placeholders with values from
// the passed object; unknown keys render as `(none)` so a missing field never
// silently leaks the placeholder syntax into a user-visible issue/PR body.
function renderTemplate(template, vars = {}) {
  return template.replace(/\$\{([a-zA-Z_][a-zA-Z0-9_]*)\}/g, (_, key) => {
    const v = vars[key];
    if (v === null || v === undefined || v === "") return "(none)";
    if (Array.isArray(v)) return v.join("\n");
    return String(v);
  });
}

// ============================================================================
// CLI parsing
// ============================================================================

function parseCliArgs(argv) {
  const opts = {
    dryRun: false,
    artifactDate: null,
    maxRetries: DEFAULT_MAX_RETRIES,
    fixturePath: null,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--dry-run") {
      opts.dryRun = true;
    } else if (arg === "--artifact-date" && i + 1 < argv.length) {
      opts.artifactDate = argv[++i];
    } else if (arg === "--max-retries" && i + 1 < argv.length) {
      const n = parseInt(argv[++i], 10);
      if (Number.isNaN(n) || n < 0) {
        throw new Error(`--max-retries must be a non-negative integer, got: ${argv[i]}`);
      }
      opts.maxRetries = n;
    } else if (arg === "--fixture-path" && i + 1 < argv.length) {
      opts.fixturePath = argv[++i];
    } else if (arg.startsWith("--")) {
      throw new Error(`unknown CLI flag: ${arg}`);
    }
  }
  return opts;
}

function todayUtcIso() {
  const d = new Date();
  const yyyy = d.getUTCFullYear();
  const mm = String(d.getUTCMonth() + 1).padStart(2, "0");
  const dd = String(d.getUTCDate()).padStart(2, "0");
  return `${yyyy}-${mm}-${dd}`;
}

function isValidDateString(s) {
  return /^\d{4}-\d{2}-\d{2}$/.test(s);
}

function generateCspNonce() {
  // Base64-encoded 16-byte random, URL-safe so it doesn't break HTML attrs.
  return crypto.randomBytes(16).toString("base64").replace(/[+/]/g, (c) =>
    c === "+" ? "-" : "_"
  );
}

