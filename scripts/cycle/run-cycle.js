// run-cycle.js — Orchestrator for the weekly AI reinvention cycle.
//
// Invoked by anthropics/claude-code-action@v1 (SHA-pinned per DC14) via the
// cron workflow (U6). The action's prompt (scripts/cycle/prompts/cycle.md)
// instructs Claude Code to run this Node script; the script marshals inputs,
// validates outputs, runs smoke gates, and writes the archive.
//
// What this script DOES NOT do:
//   - It does not call the Anthropic API directly. The Author and Editor
//     "calls" below are stub functions whose real implementation comes from
//     Claude Code's Agent tool at runtime. In production, the cycle.md
//     prompt's invocation of this script overrides the stubs by spawning
//     subagents and feeding their structured output through these stubs'
//     signatures.
//
//     This split is deliberate: the orchestrator's responsibility is to
//     assemble inputs and enforce gates; the LLM marshalling is Claude
//     Code's responsibility. Keeping them separated means the orchestrator
//     is fully unit-testable without mocking an API.
//   - It does not call git. Staging happens here (file writes); commit,
//     push, and PR open are the U6 workflow's job.
//
// CLI args:
//   --dry-run                 Use stub Author output from a fixture; write
//                              archive to /tmp/ instead of archive/YYYY-MM-DD/
//   --artifact-date YYYY-MM-DD
//                              Override the cycle date (default: today UTC)
//   --max-retries N           Author/Editor revision loop cap (default: 3)
//   --fixture-path PATH       For --dry-run, where to read the stub Author
//                              output from (default: stub fixture below)
//
// Exit codes:
//   0  Success — archive written and staged
//   1  Author/Editor revision loop exhausted retries
//   2  Schema or freeze error after all retries
//   3  Smoke or source-scan gate exhausted retries
//   4  Misconfiguration (missing configs, malformed CLI args)
//
// Final stdout line: a single JSON object the GitHub Action parses to fill
// in the PR description or failure-issue body.

