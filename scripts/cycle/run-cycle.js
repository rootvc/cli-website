function readJsConfig(relativePath) {
  // The existing CLI configs (portfolio.js, team.js, etc.) assign to a top-
  // level const and only conditionally module.exports. For configs that
  // DON'T export (older ones), we evaluate them in a vm sandbox and read
  // the named global. For configs that DO export (firm.js and onward), we
  // can just require() them directly.
  const abs = path.join(REPO_ROOT, relativePath);
  if (!fs.existsSync(abs)) {
    throw new Error(`config missing: ${relativePath}`);
  }
  try {
    // Try direct require first — works if the config has module.exports.
    delete require.cache[require.resolve(abs)];
    const direct = require(abs);
    if (direct && typeof direct === "object" && Object.keys(direct).length > 0) {
      return direct;
    }
  } catch (e) {
    // Fall through to vm-eval path.
  }
  const source = fs.readFileSync(abs, "utf8");
  // Derive the variable name from the file basename — "portfolio.js" =>
  // "portfolio". Append a module.exports assignment so we can pluck it out.
  const constName = path.basename(relativePath, ".js");
  const wrapped = `${source}\n;module.exports = (typeof ${constName} !== 'undefined') ? ${constName} : {};`;
  const vm = require("node:vm");
  const sandbox = { module: { exports: {} }, console };
  sandbox.global = sandbox;
  vm.runInNewContext(wrapped, sandbox);
  return sandbox.module.exports;
}

function readTextConfig(relativePath) {
  const abs = path.join(REPO_ROOT, relativePath);
  if (!fs.existsSync(abs)) return "";
  return fs.readFileSync(abs, "utf8");
}

